/**
 * Fills data/scripture-for-today-kjv.ts from the KJV rows in bible_verse.
 * Run: npx tsx --env-file=.env scripts/generate-scripture-for-today-kjv.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import pg from "pg";
import { parseScriptureReference } from "../lib/scripture-reference";
import { SCRIPTURE_FOR_TODAY_REFERENCES } from "../lib/scripture-for-today-refs";

function databaseUrl(): string {
  const fromEnv = process.env.DATABASE_URL?.trim();
  if (fromEnv) return fromEnv;
  const file = readFileSync(".env", "utf8");
  const match = file.match(/^DATABASE_URL=(.*)$/m);
  if (!match?.[1]) throw new Error("DATABASE_URL is not set");
  return match[1].trim().replace(/^["']|["']$/g, "");
}

async function main() {
  const client = new pg.Client({
    connectionString: databaseUrl(),
    ssl: process.env.NODE_ENV === "production" ? { rejectUnauthorized: false } : false,
  });
  await client.connect();
  const rows: {
    reference: string;
    bookId: number;
    chapter: number;
    verse: number;
    text: string;
  }[] = [];
  const missing: string[] = [];

  try {
    for (const reference of SCRIPTURE_FOR_TODAY_REFERENCES) {
      const parsed = parseScriptureReference(reference);
      if (!parsed?.verse) {
        missing.push(`${reference} (unparsed)`);
        continue;
      }
      const result = await client.query<{ text: string }>(
        `SELECT text FROM bible_verse
         WHERE translation_id = $1 AND book_id = $2 AND chapter = $3 AND verse = $4
         LIMIT 1`,
        ["KJV", parsed.bookId, parsed.chapter, parsed.verse],
      );
      const text = result.rows[0]?.text?.replace(/\s+/g, " ").trim() ?? "";
      if (!text) {
        missing.push(reference);
        continue;
      }
      rows.push({
        reference,
        bookId: parsed.bookId,
        chapter: parsed.chapter,
        verse: parsed.verse,
        text,
      });
    }
  } finally {
    await client.end();
  }

  if (missing.length > 0 || rows.length !== 366) {
    console.error(`Expected 366 KJV verses, wrote none. Missing ${missing.length}:`);
    for (const reference of missing) console.error(reference);
    process.exitCode = 1;
    return;
  }

  const body = rows
    .map(
      (row) =>
        `  { reference: ${JSON.stringify(row.reference)}, bookId: ${row.bookId}, chapter: ${row.chapter}, verse: ${row.verse}, text: ${JSON.stringify(row.text)} },`,
    )
    .join("\n");
  writeFileSync(
    "data/scripture-for-today-kjv.ts",
    `/* Generated by scripts/generate-scripture-for-today-kjv.ts from bible_verse. Do not edit verse words by hand. */\nexport interface ScriptureForTodayVerse {\n  reference: string;\n  bookId: number;\n  chapter: number;\n  verse: number;\n  text: string;\n}\n\nexport const SCRIPTURE_FOR_TODAY_KJV: readonly ScriptureForTodayVerse[] = [\n${body}\n];\n`,
  );
  console.log(`Wrote ${rows.length} KJV verses.`);
}

main().catch((err: unknown) => {
  const message = err instanceof Error ? err.message : "generation failed";
  console.error(message.replace(/postgres(?:ql)?:\/\/\S+/gi, "[database]"));
  process.exitCode = 1;
});
